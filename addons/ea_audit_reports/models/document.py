import base64
import hashlib

from odoo import api, fields, models

from ..rules import rule_error
from ..services.docx_builder import DOCX_MIME, block


class Document(models.Model):
    """A generated letter or report, filed under a task, with its versions (lib/documents.ts).
    Nothing writes one but the engine: the plain ORM entry points refuse a user."""

    _name = "ea.audit.document"
    _inherit = ["ea.audit.tool.record"]
    _description = "Generated audit document"
    _order = "code, title"
    _rec_name = "title"

    file_item_id = fields.Many2one("ea.audit.file.item", string="Task", required=True, index=True, ondelete="restrict")
    code = fields.Char(related="file_item_id.code", store=True, index=True)
    title = fields.Char(required=True)
    kind = fields.Selection(
        [("letter", "Letter"), ("report", "Report"), ("workpaper", "Working paper")], required=True, default="letter", index=True,
    )
    language = fields.Selection([("fr", "French"), ("en", "English")], default=lambda self: self.env["ea.audit.engagement"]._ea_firm_language(), required=True)
    current_version = fields.Integer(default=0)
    restricted = fields.Boolean(help="Partners only: the disclosure of criminal facts (spec 12.5.6).")
    version_ids = fields.One2many("ea.audit.document.version", "document_id", string="Versions")
    created_by_id = fields.Many2one("res.users", string="Generated by", ondelete="restrict")
    current_version_id = fields.Many2one("ea.audit.document.version", string="Latest version", compute="_compute_current", compute_sudo=True)
    current_sha256 = fields.Char(related="current_version_id.sha256", string="SHA-256")

    _item_kind_title_uniq = models.Constraint(
        "UNIQUE(file_item_id, kind, title)", "This document already exists on this task.",
    )

    @api.depends("version_ids", "current_version")
    def _compute_current(self):
        for document in self:
            document.current_version_id = document.version_ids.filtered(
                lambda v: v.version_no == document.current_version
            )[:1]

    def _ea_add_version(self, content, mime, note, blocks=None, filename=None):
        """The next version, its bytes in an attachment that follows this record's access."""
        self.ensure_one()
        number = self.current_version + 1
        Version = self.env["ea.audit.document.version"].sudo()
        extension = "docx" if mime == DOCX_MIME else (filename.rsplit(".", 1)[-1] if filename and "." in filename else "bin")
        version = Version.create({
            "engagement_id": self.engagement_id.id,
            "document_id": self.id,
            "version_no": number,
            "mime": mime,
            "byte_size": len(content),
            "sha256": hashlib.sha256(content).hexdigest(),
            "note": note,
            "blocks": blocks,
            "created_by_id": self.env.user.id,
        })
        version.attachment_id = self.env["ir.attachment"].sudo().create({
            "name": "%s v%d.%s" % (self.title, number, extension),
            "datas": base64.b64encode(content),
            "mimetype": mime,
            "res_model": version._name,
            "res_id": version.id,
        })
        self.sudo().current_version = number
        return version

    def action_download(self):
        self.ensure_one()
        self.sudo().engagement_id.with_env(self.env)._ea_require_access()
        attachment = self.sudo().current_version_id.attachment_id
        if not attachment:
            raise rule_error(self.env, "not-found")
        return {"type": "ir.actions.act_url", "target": "self", "url": "/web/content/%d?download=true" % attachment.id}

    def action_print_pdf(self):
        self.ensure_one()
        self.sudo().engagement_id.with_env(self.env)._ea_require_access()
        return self.env.ref("ea_audit_reports.action_report_document").report_action(self)

    def _ea_print_blocks(self):
        """What the QWeb template prints: the blocks of the current version."""
        self.ensure_one()
        return self.sudo().current_version_id.blocks or [block("p", self.title)]


class DocumentVersion(models.Model):
    _name = "ea.audit.document.version"
    _inherit = ["ea.audit.tool.record"]
    _description = "Generated audit document version"
    _order = "document_id, version_no desc"
    _rec_name = "version_no"

    document_id = fields.Many2one("ea.audit.document", required=True, index=True, ondelete="cascade")
    restricted = fields.Boolean(related="document_id.restricted", store=True)
    version_no = fields.Integer(string="Version", required=True)
    mime = fields.Char()
    byte_size = fields.Integer()
    sha256 = fields.Char(string="SHA-256", index=True)
    note = fields.Char()
    blocks = fields.Json()
    attachment_id = fields.Many2one("ir.attachment", ondelete="restrict")
    created_by_id = fields.Many2one("res.users", string="Generated by", ondelete="restrict")

    _doc_version_uniq = models.Constraint("UNIQUE(document_id, version_no)", "A document has one row per version.")
