def rule_error(env, code, **params):
    source = MESSAGES.get(code)
    if source is None:
        return core_rule_error(env, code, **params)
    text = env._(source)
    if params:
        text = text % params
    return AuditRuleError(code, "%s [%s]" % (text, code))
